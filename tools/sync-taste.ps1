#Requires -Version 5
<#
.SYNOPSIS
  Project Command Code's learned taste into every agent's instruction file.

.DESCRIPTION
  Command Code learns preferences into .commandcode/taste/ -- global at
  ~/.commandcode/taste/, per project at <project>/.commandcode/taste/.
  Codex, OpenCode, Claude Code and Gemini CLI only read their own instruction
  file, so that taste is invisible to them. This renders the taste files into a
  delimited, generated block and injects it where each agent looks:

    global (no -Project):
      ~/.codex/AGENTS.md   (canonical; sync-agent-instructions.ps1 then copies it
                            to ~/.config/opencode/AGENTS.md and
                            ~/.commandcode/AGENTS.md)
      ~/.claude/CLAUDE.md
      ~/.gemini/GEMINI.md
    project (-Project <dir>):
      <dir>/AGENTS.md   (from <dir>/.commandcode/taste/)

  The block is fenced by TASTE:BEGIN / TASTE:END HTML comments and replaced in
  place, so re-running is idempotent. The block is generated: edit the taste
  files (or let Command Code learn), never the block.

.EXAMPLE
  .\sync-taste.ps1
  .\sync-taste.ps1 -Project C:\path\to\repo
  .\sync-taste.ps1 -Check
#>
[CmdletBinding()]
param(
    [string]$Project,
    [switch]$Check
)

$ErrorActionPreference = 'Stop'
$Utf8NoBom = New-Object System.Text.UTF8Encoding($false)
$Begin = '<!-- TASTE:BEGIN - generated by tools/sync-taste.ps1; edit .commandcode/taste/ instead -->'
$End   = '<!-- TASTE:END -->'

function Read-Text {
    param([string]$Path)
    if (Test-Path $Path) { return [System.IO.File]::ReadAllText($Path, [System.Text.Encoding]::UTF8) }
    return ''
}
function Get-TasteBody {
    param([string]$Root)
    if (-not (Test-Path $Root)) { return '' }
    $parts = New-Object System.Collections.Generic.List[string]
    $main = Join-Path $Root 'taste.md'
    if (Test-Path $main) {
        $t = (Read-Text $main).Trim()
        if ($t.Length -gt 0) { $parts.Add($t) }
    }
    Get-ChildItem $Root -Directory | Sort-Object Name | ForEach-Object {
        $f = Join-Path $_.FullName 'taste.md'
        if (Test-Path $f) {
            $t = (Read-Text $f).Trim()
            if ($t.Length -gt 0) { $parts.Add($t) }
        }
    }
    return ($parts -join "`n`n").Trim()
}

function Merge-Block {
    param([string]$Existing, [string]$Block)
    $pattern = '(?s)' + [regex]::Escape($Begin) + '.*?' + [regex]::Escape($End)
    if ($Existing -match $pattern) {
        return [regex]::Replace($Existing, $pattern, { param($m) $Block })
    }
    if ([string]::IsNullOrWhiteSpace($Existing)) { return $Block + "`n" }
    return ($Existing.TrimEnd() + "`n`n" + $Block + "`n")
}
if ($Project) {
    $tasteRoot = Join-Path $Project '.commandcode\taste'
    $targets   = @( (Join-Path $Project 'AGENTS.md') )
    $doSync    = $false
} else {
    # $env:USERPROFILE, not $HOME: Windows PowerShell sets $HOME once, when it
    # starts, and it does not follow a changed $env:USERPROFILE. The install
    # check points USERPROFILE at an empty profile, so $HOME would still point
    # at the real one and the taste block would land in the real files.
    $tasteRoot = Join-Path $env:USERPROFILE '.commandcode\taste'
    $targets   = @(
        (Join-Path $env:USERPROFILE '.codex\AGENTS.md'),
        (Join-Path $env:USERPROFILE '.claude\CLAUDE.md'),
        (Join-Path $env:USERPROFILE '.gemini\GEMINI.md')
    )
    $doSync = $true
}

$body = Get-TasteBody $tasteRoot
if ([string]::IsNullOrWhiteSpace($body)) {
    Write-Output "no taste found at $tasteRoot - nothing to do"
    exit 0
}
$block = $Begin + "`n" + $body + "`n" + $End

$drift = $false
foreach ($t in $targets) {
    $existing = Read-Text $t
    $merged = Merge-Block -Existing $existing -Block $block
    if ($Check) {
        if ($merged -cne $existing) { Write-Output "DRIFT  $t"; $drift = $true }
        else { Write-Output "ok     $t" }
        continue
    }
    if ($merged -cne $existing) {
        $dir = Split-Path $t -Parent
        if (-not (Test-Path $dir)) { New-Item -ItemType Directory -Force -Path $dir | Out-Null }
        [System.IO.File]::WriteAllText($t, $merged, $Utf8NoBom)
        Write-Output "updated $t"
    } else {
        Write-Output "ok      $t"
    }
}

if ($Check) { if ($drift) { exit 2 } else { exit 0 } }

if ($doSync) {
    $sync = Join-Path $PSScriptRoot 'sync-agent-instructions.ps1'
    if (Test-Path $sync) { & $sync }
}